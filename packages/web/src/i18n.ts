export type StringKey = keyof typeof strings.he;
// Every language must define every key; a missing one fails the build here.
const _complete: Record<Lang, Record<StringKey, string>> = strings;
void _complete;

export function t(lang: Lang, key: StringKey): string {
  return strings[lang][key];
}

export const locale: Record<Lang, string> = { he: "he-IL", en: "en-US", de: "de-DE", it: "it-IT" };

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v);
}

export function roleLabel(lang: Lang, role: string): string {
  const key = ("role" + role.charAt(0).toUpperCase() + role.slice(1)) as StringKey;
  return (strings[lang] as Record<string, string>)[key] ?? role;
}
